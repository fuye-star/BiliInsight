# -*- coding: utf-8 -*-
"""
开发环境配置。

启用方式：manage.py 默认读取 config.settings.dev（见 manage.py）。
特点：调试开启、日志更详细、允许所有跨域来源，方便前后端联调。
"""

from .base import *  # noqa: F401,F403  —— 继承全部基础配置

# ---------------------------------------------------------------------------
# 调试开关
# ---------------------------------------------------------------------------
# 开发环境强制打开 DEBUG：能显示详细错误页，定位问题效率高得多
DEBUG = True

# DEBUG=True 时 Django 只在 ALLOWED_HOSTS 为空时允许 localhost，
# 这里显式放开本机常见地址，避免用 127.0.0.1 之外的方式访问被拦
ALLOWED_HOSTS = ["*"]


# ---------------------------------------------------------------------------
# 开发期跨域放宽
# ---------------------------------------------------------------------------
# 开发时前端端口可能变（Vite 端口被占用会自动换），
# 因此开发环境直接允许所有来源，避免反复改配置。
# 生产环境（prod.py）会收紧为白名单。
CORS_ALLOW_ALL_ORIGINS = True


# ---------------------------------------------------------------------------
# 开发期日志
# ---------------------------------------------------------------------------
# 开发时把业务日志级别调到 DEBUG，能看到爬虫请求、SQL 等细节
LOGGING["loggers"]["apps"]["level"] = "DEBUG"           # noqa: F405
LOGGING["loggers"]["django"]["level"] = "INFO"          # noqa: F405

# 打印执行的 SQL 语句（排查 N+1 查询时非常有用）
# 打开方式：在 .env 中设置 DJANGO_LOG_SQL=True
if env_bool("DJANGO_LOG_SQL", False):  # noqa: F405
    LOGGING["loggers"]["django.db.backends"] = {        # noqa: F405
        "handlers": ["console"],
        "level": "DEBUG",
        "propagate": False,
    }


# ---------------------------------------------------------------------------
# 开发期邮件后端
# ---------------------------------------------------------------------------
# 把邮件直接打印到控制台，避免开发时误发真实邮件
EMAIL_BACKEND = "django.core.mail.backends.console.EmailBackend"
